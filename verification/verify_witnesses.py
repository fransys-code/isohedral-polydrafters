#!/usr/bin/env python3
"""Independent check of witness tilings (shares no code with search/iso.cpp).
For each witness: every announced transformation is a symmetry of the grid (an isometry preserving cells and
adjacencies); the tiles generated by the group cover a fundamental cell of the lattice exactly once; the number of
transitivity classes of tiles is recounted under the announced group, then under the full symmetry group of the tiling.
With --controls, deliberately corrupted copies of each witness must be rejected.
Usage: verify_witnesses.py WITNESSES.jsonl [--grids grilles.txt] [--controls]"""
import copy, json, math, os, sys


def charge_grilles(chemin):
    grilles, g, mots = {}, None, open(chemin).read().split()
    i = 0
    while i < len(mots):
        m = mots[i]
        if m == "grille":
            g = {"nom": mots[i + 1]}; grilles[g["nom"]] = g; i += 3
        elif m == "page":
            g["page"] = [float(x) for x in mots[i + 1:i + 5]]; i += 5
        elif m == "reseau":
            v = [int(x) for x in mots[i + 1:i + 5]]; g["v1"], g["v2"] = (v[0], v[1]), (v[2], v[3]); i += 5
        elif m == "indice_reseau_heesch_sat":
            i += 2
        elif m == "orientations":
            n = int(mots[i + 1]); i += 2
            g["orientations"] = [tuple(int(x) for x in mots[i + 6 * j:i + 6 * j + 6]) for j in range(n)]; i += 6 * n
        elif m == "cellules":
            n = int(mots[i + 1]); i += 2; g["cellules"] = {}
            for _ in range(n):
                x, y, _t, nv = (int(v) for v in mots[i:i + 4]); i += 4
                g["cellules"][(x, y)] = {(int(mots[i + 2 * j]), int(mots[i + 2 * j + 1])) for j in range(nv)}; i += 2 * nv
        else:
            raise ValueError(m)
    return grilles


def croix(u, v):
    return u[0] * v[1] - u[1] * v[0]


class Reseau:
    def __init__(self, u, w):
        if croix(u, w) < 0:
            u, w = w, u
        self.u, self.w, self.det = u, w, croix(u, w)
        if self.det == 0:
            raise ValueError("degenerate lattice")

    def reduit(self, p):
        s, t = croix(p, self.w) // self.det, croix(self.u, p) // self.det
        return (p[0] - s * self.u[0] - t * self.w[0], p[1] - s * self.u[1] - t * self.w[1])

    def contient(self, p):
        return croix(p, self.w) % self.det == 0 and croix(self.u, p) % self.det == 0


def engendre(vecteurs):
    """Basis of the sublattice of Z^2 generated by integer vectors."""
    a, b = (0, 0), (0, 0)
    for v in vecteurs:
        while v[1] != 0:
            if b[1] == 0:
                b, v = v, b
            else:
                q = v[1] // b[1]
                v, b = b, (v[0] - q * b[0], v[1] - q * b[1])
        if v[0] != 0:
            a = (math.gcd(a[0], v[0]), 0)
    return a, b


class Grille:
    def __init__(self, g):
        self.g = g
        self.res = Reseau(g["v1"], g["v2"])
        self.reps = {self.res.reduit(p): (p, v) for p, v in g["cellules"].items()}
        e0x, e0y, e1x, e1y = g["page"]
        self.gram = (e0x * e0x + e0y * e0y, e0x * e1x + e0y * e1y, e1x * e1x + e1y * e1y)

    def voisins(self, p):
        r = self.reps.get(self.res.reduit(p))
        return None if r is None else r[1]

    def est_symetrie(self, t):
        a, b, c, d, e, f = t
        g00, g01, g11 = self.gram
        n = lambda x, y: g00 * x * x + 2 * g01 * x * y + g11 * y * y
        if abs(n(a, d) - g00) > 1e-9 or abs(n(b, e) - g11) > 1e-9 or abs(n(a + b, d + e) - n(1, 1)) > 1e-9:
            return False
        for v in (self.g["v1"], self.g["v2"]):
            if not self.res.contient((a * v[0] + b * v[1], d * v[0] + e * v[1])):
                return False
        for p, vs in self.g["cellules"].items():
            ws = self.voisins((a * p[0] + b * p[1] + c, d * p[0] + e * p[1] + f))
            if ws is None or ws != {(a * x + b * y, d * x + e * y) for x, y in vs}:
                return False
        return True

    def connexe(self, cellules):
        cs = set(cellules); vus = {cellules[0]}; pile = [cellules[0]]
        while pile:
            p = pile.pop()
            for d in self.voisins(p):
                q = (p[0] + d[0], p[1] + d[1])
                if q in cs and q not in vus:
                    vus.add(q); pile.append(q)
        return len(vus) == len(cs)


def applique(t, p):
    return (t[0] * p[0] + t[1] * p[1] + t[2], t[3] * p[0] + t[4] * p[1] + t[5])


def compose(s, t):
    return (s[0] * t[0] + s[1] * t[3], s[0] * t[1] + s[1] * t[4], s[0] * t[2] + s[1] * t[5] + s[2],
            s[3] * t[0] + s[4] * t[3], s[3] * t[1] + s[4] * t[4], s[3] * t[2] + s[4] * t[5] + s[5])


def canon(L, tuile):
    """Representative of a tile modulo L: the translate whose smallest cell is reduced."""
    m = min(tuile); r = L.reduit(m); d = (m[0] - r[0], m[1] - r[1])
    return frozenset((p[0] - d[0], p[1] - d[1]) for p in tuile)


def orbites(tuiles, symetries, L):
    """Number of orbits of tiles (given modulo L) under symmetries that normalise L."""
    parent = {t: t for t in tuiles}

    def racine(x):
        while parent[x] != x:
            parent[x] = parent[parent[x]]; x = parent[x]
        return x
    for s in symetries:
        for t in tuiles:
            im = canon(L, [applique(s, p) for p in t])
            if im not in parent:
                return None
            parent[racine(t)] = racine(im)
    return len({racine(t) for t in tuiles})


def verifie(G, cellules, temoin):
    cellules = [tuple(c) for c in cellules]
    n = len(cellules)
    if len(set(cellules)) != n or any(G.voisins(p) is None for p in cellules):
        return {"valid": False, "error": "invalid cells"}
    if not G.connexe(cellules):
        return {"valid": False, "error": "shape not connected"}
    l1, l2 = (tuple(v) for v in temoin["lattice"])
    if not (G.res.contient(l1) and G.res.contient(l2)) or croix(l1, l2) == 0:
        return {"valid": False, "error": "invalid tiling lattice"}
    L = Reseau(l1, l2)
    groupe = [tuple(t) for t in temoin["group"]]
    placements = [tuple(t) for t in temoin["tiles"]]
    for t in groupe + placements:
        if not G.est_symetrie(t):
            return {"valid": False, "error": f"{t} is not a symmetry of the grid"}
    for t in groupe:
        for v in (L.u, L.w):
            if not L.contient((t[0] * v[0] + t[1] * v[1], t[3] * v[0] + t[4] * v[1])):
                return {"valid": False, "error": "the group does not normalise the lattice"}
    red = lambda t: t[:2] + (L.reduit((t[2], t[5]))[0],) + t[3:5] + (L.reduit((t[2], t[5]))[1],)
    H = {red((1, 0, 0, 0, 1, 0))}; file = list(H)
    while file:
        x = file.pop()
        for s in groupe:
            y = red(compose(s, x))
            if y not in H:
                H.add(y); file.append(y)
                if len(H) > 5000:
                    return {"valid": False, "error": "group too large"}
    mailles = L.det // G.res.det * len(G.g["cellules"])
    plan = {canon(L, [applique(h, applique(t, p)) for p in cellules]) for h in H for t in placements}
    couvert = set()
    for tuile in plan:
        tore = {L.reduit(p) for p in tuile}
        if len(tore) != n or couvert & tore:
            return {"valid": False, "error": "overlap"}
        couvert |= tore
    if len(couvert) != mailles:
        return {"valid": False, "error": f"incomplete cover ({len(couvert)}/{mailles})"}
    k_groupe = orbites(list(plan), H, L)
    def normal(pts):
        m = min(pts); return m, frozenset((p[0] - m[0], p[1] - m[1]) for p in pts)
    trans = [L.u, L.w]
    t0 = next(iter(plan))
    m0, f0 = normal(t0)
    for tuile in plan:
        mt, ft = normal(tuile)
        if ft != f0:
            continue
        d = (mt[0] - m0[0], mt[1] - m0[1])
        if G.res.contient(d) and all(canon(L, [(p[0] + d[0], p[1] + d[1]) for p in c]) in plan for c in plan):
            trans.append(d)
    c1 = lambda v: (croix(v, G.g["v2"]) // G.res.det, croix(G.g["v1"], v) // G.res.det)
    a, b = engendre([c1(v) for v in trans])
    xy = lambda c: (c[0] * G.g["v1"][0] + c[1] * G.g["v2"][0], c[0] * G.g["v1"][1] + c[1] * G.g["v2"][1])
    LT = Reseau(xy(a), xy(b))
    planT = {canon(LT, t) for t in plan}
    syms = []
    t0 = next(iter(planT))
    for o in G.g["orientations"]:
        if not all(LT.contient((o[0] * v[0] + o[1] * v[1], o[3] * v[0] + o[4] * v[1])) for v in (LT.u, LT.w)):
            continue
        im = [applique(o, p) for p in t0]
        mi, fi = normal(im)
        for tuile in planT:
            mt, ft = normal(tuile)
            if fi != ft:
                continue
            s = (o[0], o[1], o[2] + mt[0] - mi[0], o[3], o[4], o[5] + mt[1] - mi[1])
            if G.est_symetrie(s) and all(canon(LT, [applique(s, p) for p in c]) in planT for c in planT):
                syms.append(s)
    k_pavage = orbites(list(planT), syms, LT)
    return {"valid": True, "tiles_per_cell": len(plan), "group_order": len(H), "classes_under_given_group": k_groupe,
            "tiles_per_primitive_cell": len(planT), "full_symmetry_order": len(syms), "classes_under_full_symmetry": k_pavage}


def check(grilles, r):
    v = verifie(grilles[r["grid"]], r["cells"], r["witness"])
    k = r["isohedral_number"]
    ok = v["valid"] and len(r["cells"]) == r["n"] and v["classes_under_given_group"] is not None \
        and v["classes_under_given_group"] <= k and v["classes_under_full_symmetry"] == k
    return ok, v


def corrupted(grille, r):
    w = r["witness"]
    a = copy.deepcopy(r); a["witness"]["tiles"] = w["tiles"][:-1]
    yield "one class of tiles removed", a
    b = copy.deepcopy(r); b["witness"]["tiles"][0][2] += grille.g["v1"][0]; b["witness"]["tiles"][0][5] += grille.g["v1"][1]
    yield "one tile shifted by a grid translation", b
    c = copy.deepcopy(r); c["witness"]["tiles"][0][2] += 1
    yield "one tile moved off the grid", c
    d = copy.deepcopy(r); d["witness"]["tiles"][0] = w["tiles"][1]
    yield "one tile replaced by a copy of another", d
    e = copy.deepcopy(r); e["isohedral_number"] += 1
    yield "announced number increased by one", e


def main():
    args = sys.argv[1:]
    chemin_g = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "search", "grilles.txt")
    controles, fichiers = False, []
    i = 0
    while i < len(args):
        if args[i] == "--grids":
            chemin_g = args[i + 1]; i += 2
        elif args[i] == "--controls":
            controles = True; i += 1
        else:
            fichiers.append(args[i]); i += 1
    grilles = {nom: Grille(g) for nom, g in charge_grilles(chemin_g).items()}
    total = mauvais = rejets = acceptes = 0
    for f in fichiers:
        for ligne in open(f):
            r = json.loads(ligne)
            ok, v = check(grilles, r)
            total += 1; mauvais += not ok
            print("OK  " if ok else "FAIL", r["id"], f"{r['n']}-{r['grid']}", "announced", r["isohedral_number"], json.dumps(v), flush=True)
            if controles:
                for nom, c in corrupted(grilles[r["grid"]], r):
                    if check(grilles, c)[0]:
                        acceptes += 1; print("FAIL corrupted witness accepted:", r["id"], nom)
                    else:
                        rejets += 1
    print(f"{total} witnesses checked, {mauvais} failure(s)")
    if controles:
        print(f"{rejets + acceptes} corrupted witnesses, {rejets} rejected, {acceptes} wrongly accepted")
    sys.exit(1 if mauvais or acceptes else 0)


if __name__ == "__main__":
    main()
